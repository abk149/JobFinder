#!/usr/bin/env node
// Installs a double-clickable launcher at ~/Desktop/JobFinder.command
// When clicked: starts the server in the target project dir, opens the dashboard.
//
// Usage:
//   node scripts/install-launcher.js                 # points at this checkout
//   node scripts/install-launcher.js /path/to/proj   # points somewhere else
//
// The explicit-path form exists so the launcher can target a copy on an external
// drive without having to run this script from that drive.

const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');

const argDir = process.argv[2];
const projectDir = path.resolve(argDir || path.resolve(__dirname, '..'));

if (!fs.existsSync(path.join(projectDir, 'package.json'))) {
  console.error(`✗ No package.json in ${projectDir}`);
  console.error('  Point this at a JobFinder checkout, e.g.:');
  console.error('    node scripts/install-launcher.js "/path/to/JobFinder"');
  process.exit(1);
}

const desktop = path.join(os.homedir(), 'Desktop');
const launcher = path.join(desktop, 'JobFinder.command');

// If the project lives on a mounted volume, the launcher must check the drive is
// actually plugged in — otherwise `cd` fails, the Terminal window closes with a
// cryptic error, or npm starts installing into a half-present path.
const onVolume = projectDir.startsWith('/Volumes/');
const volumeRoot = onVolume ? '/' + projectDir.split('/').slice(1, 3).join('/') : null;

const mountGuard = onVolume ? `
# ── External drive check ────────────────────────────────────────────────
if [ ! -d "${volumeRoot}" ]; then
  echo ""
  echo "  ✗ Drive not connected: ${volumeRoot}"
  echo "    Plug the drive in and run this again."
  echo ""
  read -n 1 -s -r -p "  Press any key to close…"
  exit 1
fi
if [ ! -f "${projectDir}/package.json" ]; then
  echo ""
  echo "  ✗ Drive is mounted but JobFinder isn't at:"
  echo "    ${projectDir}"
  echo ""
  read -n 1 -s -r -p "  Press any key to close…"
  exit 1
fi
` : '';

const script = `#!/bin/bash
# JobFinder launcher — generated by install-launcher.js
# Project: ${projectDir}
set -e
${mountGuard}
cd "${projectDir}"

# Pick up nvm / homebrew node paths in case Terminal can't find them
export PATH="/opt/homebrew/bin:/usr/local/bin:$PATH"
if [ -s "$HOME/.nvm/nvm.sh" ]; then . "$HOME/.nvm/nvm.sh"; fi

if ! command -v node >/dev/null 2>&1; then
  echo "  ✗ Node.js not found on PATH. Install it from https://nodejs.org and retry."
  read -n 1 -s -r -p "  Press any key to close…"
  exit 1
fi

# Ollama powers autofill writeups and interview prep. Start it if it's installed
# but not currently listening, so the dashboard isn't crippled after a reboot.
if command -v ollama >/dev/null 2>&1; then
  if ! curl -s -m 2 http://127.0.0.1:11434/api/tags >/dev/null 2>&1; then
    echo "[JobFinder] Starting Ollama…"
    (ollama serve >/dev/null 2>&1 &)
    sleep 2
  fi
else
  echo "[JobFinder] Note: Ollama not found — AI writeups and interview prep will be inactive."
fi

if [ ! -d node_modules ]; then
  echo "[JobFinder] First-time setup: installing dependencies (this can take a few minutes)…"
  npm install
fi

if [ ! -d .next ]; then
  echo "[JobFinder] Building production bundle…"
  npm run build
fi

PORT=3737
if lsof -nP -iTCP:\$PORT -sTCP:LISTEN >/dev/null 2>&1; then
  echo "[JobFinder] Something is already running on port \$PORT — opening that instead."
  open "http://localhost:\$PORT"
  read -n 1 -s -r -p "  Press any key to close…"
  exit 0
fi

(sleep 3 && open "http://localhost:\$PORT") &
echo "[JobFinder] Starting dashboard at http://localhost:\$PORT"
echo "[JobFinder] Running from: ${projectDir}"
echo "[JobFinder] Close this Terminal window to stop the server."
exec npm run start
`;

fs.writeFileSync(launcher, script, { mode: 0o755 });
fs.chmodSync(launcher, 0o755);
console.log(`✅ Installed launcher at ${launcher}`);
console.log(`   → runs from: ${projectDir}`);
if (onVolume) console.log(`   → verifies ${volumeRoot} is mounted first`);
console.log(`   Double-click "JobFinder.command" on your Desktop to launch.`);
